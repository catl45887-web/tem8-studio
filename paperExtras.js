      "Consumption as a path to cultivation",
      "Consumption, for George Simmel, German sociologist and philosopher, lies at the heart of the process through which people become cultivated, that is, grow to become participating, reflective members of society. This is because consumption provides an excellent site for the interaction between subject and object, which Simmel believed to be the key to cultivation. Subjectivity, the uniquely human capacity for self-reflection, which allows for the self-conscious construction of action and identity, is not naturally endowed; it only develops through the creative tension provided by interaction with objects (including people) existing in the world. For Simmel, consumption provides a vital forum for this subject-object interaction. Through consumption, people come to understand, instill meaning in, and act upon objects encountered in the world. Consumption provides people with the opportunity to refine themselves through interaction with objects in the world. In addition, by confronting, adapting, and integrating various worldviews directly or indirectly demonstrated in consumption objects, people not only realize their potential as unique human beings, they also become well-socialized members of a society."
